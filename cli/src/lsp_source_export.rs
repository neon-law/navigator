//! ENG-931: the allowlisted, versioned extraction that keeps `lsp`'s source
//! public without mirroring the whole private monorepo.
//!
//! "Keep LSP source and binaries public through an allowlisted, versioned
//! extraction of `lsp` and the `rules` dependency it needs; never mirror the
//! whole private monorepo" is ENG-931's own wording for this half of public
//! distribution. The binaries are already covered — `deploy.yml` mirrors every
//! `navigator-lsp-<tag>-<platform>` archive onto the public distribution host
//! alongside the CLI's (see `RELEASES_REPO` in `lsp_download.rs`) — so what
//! remains is the SOURCE: a reader, or a third-party editor extension author,
//! has to be able to read and build `navigator-lsp` without the private
//! monorepo, and `rules` is the one workspace crate it depends on.
//!
//! This module computes WHAT that export carries and HOW its two generated
//! manifests are shaped. It performs no I/O of its own — no git, no network,
//! no filesystem writes — and is not wired to any `navigator ops` subcommand
//! or scheduled job yet. Wiring it to an actual target repository is the
//! operational cutover ENG-931 leaves open; this proves the allowlist and
//! both generated manifests are correct against the REAL workspace today, so
//! that wiring is a thin, already-tested shell rather than a design still to
//! prove.
//!
//! # What is copied verbatim, and what is regenerated
//!
//! [`ALLOWED_PATHS`] is copied byte-for-byte: `lsp/` in full (its own tests
//! included — they need nothing outside the crate) and `rules/src` — never
//! `rules/tests`, which needs the `workflows` crate this export does not
//! carry. `LICENSE`, `LICENSE-MIT`, `LICENSE-APACHE-2`, and `NOTICE` travel too,
//! for the same reason every release archive carries them.
//!
//! `rules/Cargo.toml` is NOT in that list: it is regenerated by
//! [`generate_rules_manifest`], dropping the real file's `[dev-dependencies]`
//! (which name `workflows`, a crate this export does not carry — carrying the
//! dependency without the crate is a manifest that cannot resolve) while
//! keeping its `[dependencies]` untouched. The export's own root `Cargo.toml`
//! is generated fresh by [`generate_root_manifest`], since there is no
//! workspace root to copy one from — only the two crates that need it exist
//! outside the monorepo.

use std::collections::BTreeSet;

use anyhow::{Context, Result};

/// Every path this extraction carries out of the workspace, copied verbatim,
/// and nothing else. This constant, together with `rules/Cargo.toml` being
/// regenerated rather than copied (see the module docs), is the whole
/// allowlist — the boundary "never mirror the whole private monorepo" reduces
/// to "a caller may only ever read these entries."
pub const ALLOWED_PATHS: &[&str] = &[
    "lsp",
    "rules/src",
    "LICENSE",
    "LICENSE-APACHE-2",
    "LICENSE-MIT",
    "NOTICE",
];

/// The `[workspace.dependencies]` keys the export's two crates need, read from
/// their own manifests rather than hand-copied, so a dependency added to
/// either crate is captured automatically and one no longer used drops out on
/// its own.
///
/// Scans `lsp`'s `[dependencies]` and `[dev-dependencies]` (its own tests
/// travel with it) and `rules`' `[dependencies]` only — never `rules`'
/// `[dev-dependencies]`, which the regenerated manifest drops (see the module
/// docs) and which name `workflows`, a crate this export never carries.
pub fn required_dependency_keys(
    lsp_manifest: &str,
    rules_manifest: &str,
) -> Result<BTreeSet<String>> {
    let mut keys = BTreeSet::new();
    collect_workspace_dependency_keys(
        lsp_manifest,
        &["dependencies", "dev-dependencies"],
        &mut keys,
    )?;
    collect_workspace_dependency_keys(rules_manifest, &["dependencies"], &mut keys)?;
    Ok(keys)
}

/// Add every key of every named table in `manifest` whose value is a
/// `{ workspace = true }` inline table (this workspace's only spelling for a
/// workspace dependency; a bare version string never names one) into `keys`.
fn collect_workspace_dependency_keys(
    manifest: &str,
    tables: &[&str],
    keys: &mut BTreeSet<String>,
) -> Result<()> {
    let document: toml::Value =
        toml::from_str(manifest).context("parse a crate manifest as TOML")?;
    for table_name in tables {
        let Some(table) = document.get(table_name).and_then(toml::Value::as_table) else {
            continue;
        };
        for (name, value) in table {
            let is_workspace_dependency = value
                .get("workspace")
                .and_then(toml::Value::as_bool)
                .unwrap_or(false);
            if is_workspace_dependency {
                keys.insert(name.clone());
            }
        }
    }
    Ok(())
}

/// Build the export's standalone `rules/Cargo.toml`: the real package
/// identity, concrete rather than `.workspace = true` (there is no workspace
/// left to inherit from), and the real `[dependencies]` table, untouched and
/// still `.workspace = true` — the export's generated root `Cargo.toml`
/// defines those same keys, so the two agree by construction.
pub fn generate_rules_manifest(rules_manifest: &str, package_version: &str) -> Result<String> {
    let document: toml::Value = toml::from_str(rules_manifest).context("parse rules/Cargo.toml")?;
    let dependencies = document
        .get("dependencies")
        .cloned()
        .ok_or_else(|| anyhow::anyhow!("rules/Cargo.toml has no [dependencies] table"))?;

    let mut package = toml::map::Map::new();
    package.insert("name".into(), toml::Value::String("rules".into()));
    package.insert(
        "version".into(),
        toml::Value::String(package_version.to_string()),
    );
    package.insert("edition".into(), toml::Value::String("2021".into()));

    let mut root = toml::map::Map::new();
    root.insert("package".into(), toml::Value::Table(package));
    root.insert("dependencies".into(), dependencies);

    toml::to_string_pretty(&toml::Value::Table(root))
        .context("serialize the generated rules/Cargo.toml")
}

/// Build the export's root `Cargo.toml`: a two-member workspace naming `lsp`
/// and `rules`, with `[workspace.package]` copied from the real workspace
/// manifest's own table and `[workspace.dependencies]` narrowed to exactly
/// `dependency_keys` — never the full table, which would defeat the
/// allowlist by naming crates and versions from parts of the workspace this
/// export never carries.
pub fn generate_root_manifest(
    workspace_manifest: &str,
    dependency_keys: &BTreeSet<String>,
) -> Result<String> {
    let document: toml::Value =
        toml::from_str(workspace_manifest).context("parse the workspace manifest as TOML")?;
    let workspace_package = document
        .get("workspace")
        .and_then(|workspace| workspace.get("package"))
        .and_then(toml::Value::as_table)
        .ok_or_else(|| anyhow::anyhow!("the manifest has no [workspace.package] table"))?;
    let all_dependencies = document
        .get("workspace")
        .and_then(|workspace| workspace.get("dependencies"))
        .and_then(toml::Value::as_table)
        .ok_or_else(|| anyhow::anyhow!("the manifest has no [workspace.dependencies] table"))?;

    let mut narrowed_dependencies = toml::map::Map::new();
    for key in dependency_keys {
        let value = all_dependencies.get(key).ok_or_else(|| {
            anyhow::anyhow!(
                "`{key}` is not a [workspace.dependencies] key in the real workspace manifest"
            )
        })?;
        narrowed_dependencies.insert(key.clone(), value.clone());
    }

    let mut workspace = toml::map::Map::new();
    workspace.insert(
        "members".into(),
        toml::Value::Array(vec![
            toml::Value::String("lsp".into()),
            toml::Value::String("rules".into()),
        ]),
    );
    workspace.insert(
        "package".into(),
        toml::Value::Table(workspace_package.clone()),
    );
    workspace.insert(
        "dependencies".into(),
        toml::Value::Table(narrowed_dependencies),
    );

    let mut root = toml::map::Map::new();
    root.insert("workspace".into(), toml::Value::Table(workspace));

    toml::to_string_pretty(&toml::Value::Table(root))
        .context("serialize the generated root Cargo.toml")
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::{Path, PathBuf};

    fn workspace_root() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .canonicalize()
            .expect("workspace root exists")
    }

    fn read(relative: &str) -> String {
        let path: &Path = relative.as_ref();
        std::fs::read_to_string(workspace_root().join(path))
            .unwrap_or_else(|error| panic!("read {relative}: {error}"))
    }

    /// The allowlist names existing paths and nothing from outside `lsp` and
    /// `rules` — a regression here is exactly ENG-931's boundary breaking.
    #[test]
    fn every_allowed_path_exists_and_none_reaches_outside_lsp_or_rules() {
        for path in ALLOWED_PATHS {
            assert!(
                workspace_root().join(path).exists(),
                "`{path}` is in ALLOWED_PATHS but does not exist"
            );
            assert!(
                *path == "LICENSE"
                    || *path == "LICENSE-MIT"
                    || *path == "LICENSE-APACHE-2"
                    || *path == "NOTICE"
                    || path.starts_with("lsp")
                    || path.starts_with("rules"),
                "`{path}` is outside `lsp` and `rules` — ENG-931 forbids mirroring the rest of the \
                 workspace"
            );
        }
        assert!(
            !ALLOWED_PATHS.contains(&"rules/Cargo.toml"),
            "rules/Cargo.toml is regenerated (dropping its dev-dependencies on `workflows`), not \
             copied verbatim — see generate_rules_manifest"
        );
        assert!(
            !ALLOWED_PATHS.iter().any(|p| p.contains("rules/tests")),
            "rules/tests needs the `workflows` crate this export never carries"
        );
    }

    /// Run against the real manifests, this is the property the whole module
    /// exists to keep true: every workspace dependency `lsp` or `rules`
    /// actually declares is captured, and nothing else is invented.
    #[test]
    fn required_dependency_keys_matches_the_real_manifests_today() {
        let keys = required_dependency_keys(&read("lsp/Cargo.toml"), &read("rules/Cargo.toml"))
            .expect("both manifests parse");

        for expected in [
            "rules",
            "serde",
            "serde_json",
            "tokio",
            "anyhow",
            "url",
            "tracing",
            "tempfile",
            "chrono",
            "serde_yaml",
            "walkdir",
        ] {
            assert!(
                keys.contains(expected),
                "expected `{expected}` among the required dependency keys, got {keys:?}"
            );
        }
        assert!(
            keys.contains("rules"),
            "`rules = {{ workspace = true }}` in lsp/Cargo.toml must be captured, got {keys:?}"
        );
        assert!(
            !keys.contains("workflows"),
            "workflows must never appear — it is rules' dev-dependency, dropped from the export, \
             got {keys:?}"
        );
    }

    /// The generated `rules/Cargo.toml` builds standalone: concrete package
    /// identity, the real dependency table, and nothing pointing back at a
    /// workspace this file no longer has.
    #[test]
    fn generated_rules_manifest_is_standalone_and_carries_every_real_dependency() {
        let rendered = generate_rules_manifest(&read("rules/Cargo.toml"), "26.9.27")
            .expect("the real rules/Cargo.toml generates a manifest");
        let document: toml::Value =
            toml::from_str(&rendered).expect("the generated manifest parses");

        assert_eq!(
            document["package"]["name"].as_str(),
            Some("rules"),
            "rendered:\n{rendered}"
        );
        assert_eq!(
            document["package"]["version"].as_str(),
            Some("26.9.27"),
            "rendered:\n{rendered}"
        );
        assert!(
            document.get("dev-dependencies").is_none(),
            "the generated manifest must drop [dev-dependencies] entirely, rendered:\n{rendered}"
        );
        for expected in ["chrono", "serde", "serde_yaml", "walkdir"] {
            assert!(
                document["dependencies"].get(expected).is_some(),
                "expected `{expected}` in the generated [dependencies], rendered:\n{rendered}"
            );
        }
    }

    /// The generated root manifest is a real, parseable two-member workspace
    /// naming exactly the dependencies `required_dependency_keys` found —
    /// never the workspace's full table, which would silently readmit
    /// everything the allowlist exists to keep out.
    #[test]
    fn generated_root_manifest_is_a_two_member_workspace_with_only_the_needed_dependencies() {
        let lsp_manifest = read("lsp/Cargo.toml");
        let rules_manifest = read("rules/Cargo.toml");
        let keys = required_dependency_keys(&lsp_manifest, &rules_manifest).expect("keys resolve");

        let rendered = generate_root_manifest(&read("Cargo.toml"), &keys)
            .expect("the real workspace manifest generates a root manifest");
        let document: toml::Value =
            toml::from_str(&rendered).expect("the generated manifest parses");

        let members: Vec<&str> = document["workspace"]["members"]
            .as_array()
            .expect("members is an array")
            .iter()
            .map(|value| value.as_str().expect("a member name"))
            .collect();
        assert_eq!(members, vec!["lsp", "rules"], "rendered:\n{rendered}");

        assert_eq!(
            document["workspace"]["package"]["license"].as_str(),
            Some("MIT OR Apache-2.0"),
            "the generated manifest must keep the real workspace's licence, rendered:\n{rendered}"
        );

        let rendered_dependencies = document["workspace"]["dependencies"]
            .as_table()
            .expect("dependencies is a table");
        assert_eq!(
            rendered_dependencies.len(),
            keys.len(),
            "the generated manifest must carry exactly the required keys and no more, rendered:\n{rendered}"
        );
        for key in &keys {
            assert!(
                rendered_dependencies.contains_key(key),
                "expected `{key}` among the generated [workspace.dependencies], rendered:\n{rendered}"
            );
        }
    }

    /// `rules = { workspace = true }` inside `lsp/Cargo.toml` resolves through
    /// the real root manifest's own `rules = { path = "rules" }` entry, and
    /// that relative path is exactly as valid inside the two-member export as
    /// it is in the full workspace — both put `rules/` beside the root
    /// `Cargo.toml`. So the generated manifest carries it unchanged rather
    /// than needing a special case: a path dependency, unlike a crates.io
    /// one, IS the membership.
    #[test]
    fn the_rules_dependency_carries_over_as_the_same_relative_path() {
        let lsp_manifest = read("lsp/Cargo.toml");
        let rules_manifest = read("rules/Cargo.toml");
        let keys = required_dependency_keys(&lsp_manifest, &rules_manifest).expect("keys resolve");
        assert!(
            keys.contains("rules"),
            "expected `rules` among the required keys, got {keys:?}"
        );

        let rendered = generate_root_manifest(&read("Cargo.toml"), &keys)
            .expect("the root manifest generates");
        let document: toml::Value = toml::from_str(&rendered).expect("parses");

        assert_eq!(
            document["workspace"]["dependencies"]["rules"]["path"].as_str(),
            Some("rules"),
            "the generated [workspace.dependencies] must carry `rules` as the same relative path \
             the real workspace uses, rendered:\n{rendered}"
        );
    }
}
